import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { listProfiles, loadProfile, PROFILES_DIR, profileHash } from "../math/profile.js";
import { countSymbols } from "../math/strips.js";
import { theoreticalRtp } from "../math/theoretical.js";
import { MathProfile, SYMBOLS } from "../math/types.js";

/**
 * Writes the math sheet (PAR sheet) for every profile to docs/par-sheet.md.
 *   npm run par
 */
const pct = (x: number, d = 3) => `${(x * 100).toFixed(d)}%`;
const oneIn = (p: number) => (p > 0 ? `1 in ${Math.round(1 / p).toLocaleString()}` : "never");

function sheet(p: MathProfile): string {
  const maxBet = Math.max(...p.betLevelsCents);
  const t = theoreticalRtp(p, maxBet);
  const byBet = p.betLevelsCents.map((b) => [b, theoreticalRtp(p, b).rtp] as const);
  const out: string[] = [];
  out.push(`## ${p.id}`, "", `${p.description}`, "", `Profile hash (sha256): \`${profileHash(p)}\``, "");
  out.push("### RTP by bet", "", "| Bet | RTP |", "|---|---|");
  byBet.forEach(([b, r]) => out.push(`| ${(b / 100).toFixed(2)} | ${pct(r)} |`));
  out.push("", "### RTP breakdown (max bet)", "", "| Component | RTP |", "|---|---|");
  for (const [k, v] of Object.entries(t.components)) out.push(`| ${k} | ${pct(v)} |`);
  out.push(`| **Total** | **${pct(t.rtp)}** |`, "");
  out.push("### Feature frequency", "", "| Event | Odds per paid spin |", "|---|---|");
  out.push(`| Free spins (3+ SCATTER) | ${oneIn(t.freeSpins.triggerProbability)} |`);
  out.push(`| Free spins retrigger (per free spin) | ${oneIn(t.freeSpins.retriggerProbability)} |`);
  out.push(`| Super Wheel (3 BONUS) | ${oneIn(t.wheel.triggerProbability)} |`);
  for (const [tier, pr] of Object.entries(t.jackpotHitProbabilityPerSpin)) out.push(`| ${tier} jackpot at max bet | ${oneIn(pr)} |`);
  out.push("", `Expected free spins per trigger: ${t.freeSpins.expectedSpinsPerTrigger.toFixed(3)}; expected free-spin win: ${t.freeSpins.expectedWinPerTrigger.toFixed(2)}x bet.`, "");
  for (const [name, set] of Object.entries(p.reels)) {
    out.push(`### ${name} reel symbol counts`, "", `| Symbol | ${set.map((_, i) => `R${i + 1}`).join(" | ")} |`, `|---|${set.map(() => "---").join("|")}|`);
    const counts = set.map(countSymbols);
    for (const s of SYMBOLS) {
      if (counts.every((c) => !c.get(s))) continue;
      out.push(`| ${s} | ${counts.map((c) => c.get(s) ?? 0).join(" | ")} |`);
    }
    out.push(`| **Length** | ${set.map((s) => s.length).join(" | ")} |`, "");
  }
  return out.join("\n");
}

const profiles = listProfiles().map(loadProfile);
const p0 = profiles[0];
const intro = [
  "# Jack Vault math sheet",
  "",
  "Generated by `npm run par` from the profiles in `profiles/`. All figures are exact (computed, not simulated); `npm run sim` checks them by Monte Carlo.",
  "",
  "## Common rules",
  "",
  `- 5 reels x 4 rows, ${p0.paylines.length} fixed lines, pays left to right. Line bet = total bet / ${p0.paylines.length}.`,
  "- WILD (reels 2-5) substitutes for all symbols except SCATTER and BONUS.",
  `- SCATTER pays anywhere (x total bet): ${Object.entries(p0.scatterPays).map(([k, v]) => `${k}=${v}x`).join(", ")}. ${p0.freeSpins.triggerCount}+ award ${p0.freeSpins.spinsAwarded} free spins, all wins x${p0.freeSpins.multiplier}, retrigger +${p0.freeSpins.retriggerSpins}.`,
  `- ${p0.wheel.triggerCount} BONUS (reels 1, 3, 5) in the base game spin the Super Wheel. Jackpot segment weights scale with bet / max bet; the removed weight goes to segment ${p0.wheel.jackpotFallbackSegment}.`,
  "- Progressive jackpots: each paid spin contributes to every pool; a hit pays the pool and resets it to its seed.",
  "",
  "| Symbol | 3 | 4 | 5 |",
  "|---|---|---|---|",
  ...Object.entries(p0.paytable).map(([s, r]) => `| ${s} | ${r[3] ?? "-"} | ${r[4] ?? "-"} | ${r[5] ?? "-"} |`),
  "",
  "| Wheel segment | Weight (max bet) |",
  "|---|---|",
  ...p0.wheel.segments.map((s) => `| ${s.kind === "CREDIT" ? `${s.multiplier}x bet` : s.kind === "FREE_SPINS" ? `${s.spins} free spins` : `${s.tier} jackpot`} | ${s.weight} |`),
  "",
  "| Jackpot | Seed | Contribution |",
  "|---|---|---|",
  ...Object.entries(p0.jackpots).map(([t, j]) => `| ${t} | ${(j.seedCents / 100).toFixed(2)} | ${(j.contributionBps / 100).toFixed(2)}% of bet |`),
  "",
];
const md = [...intro, ...profiles.map(sheet)].join("\n") + "\n";
const file = join(PROFILES_DIR, "../docs/par-sheet.md");
writeFileSync(file, md);
